package bigdata_week;

import java.io.IOException;
import java.util.Scanner;

/**
 * Адриана проходит стажировку в новом дата-центре Яндекса, расположенном под Владимиром.
 * В дата-центре n серверов. Они выстроены в линию один за другим и пронумерованы от 1 до n.
 * У каждого сервера свой вес.
 * <p>
 * Для начала Адриана хочет отсортировать первые k серверов по неубыванию веса.
 * Из-за особенностей дата-центра разрешено менять местами только пару соседних серверов,
 * для этого необходимо количество энергии, равное максимальному из весов этих двух серверов.
 * <p>
 * Пока что Адриана не может выбрать конкретное число k,
 * поэтому просит вас посчитать суммарные затраты энергии на упорядочивание
 * для всех возможных значений k от 1 до n.
 * <p>
 * Формат ввода
 * В первой строке дано целое число n — количество серверов.
 * Во второй строке через пробел записаны n целых чисел wi — вес i-го сервера.
 * <p>
 * Формат вывода
 * В единственной строке выведите через пробел n целых чисел
 * resi — суммарное количество энергии, необходимое для упорядочивания первых i серверов.
 * <p>
 * Пример 1
 * Ввод
 * 3
 * 3 1 2
 * <p>
 * Вывод
 * 0 3 6
 * <p>
 * Пример 2
 * Ввод
 * 5
 * 1 4 3 2 5
 * <p>
 * Вывод
 * 0 0 4 11 11
 */
public class ServerSorting {
	
	public static void main(String[] args) throws IOException {
		Scanner scanner = new Scanner(System.in);
		
		// Читаем количество серверов
		int n = scanner.nextInt();
		
		// Создаем массив весов серверов
		int[] weights = new int[n];
		for (int i = 0; i < n; i++) {
			weights[i] = scanner.nextInt();
		}
		
		// Создаем массив для хранения результатов
		long[] results = new long[n];
		
		// Проходим по всем возможным значениям k
		for (int k = 1; k <= n; k++) {
			// Создаем копию первых k элементов
			int[] current = new int[k];
			System.arraycopy(weights, 0, current, 0, k);
			
			// Считаем энергию для текущей последовательности
			long energy = 0;
			boolean swapped;
			do {
				swapped = false;
				for (int i = 0; i < k - 1; i++) {
					if (current[i] > current[i + 1]) {
						// Меняем местами и считаем энергию
						int temp = current[i];
						current[i] = current[i + 1];
						current[i + 1] = temp;
						energy += Math.max(current[i], current[i + 1]);
						swapped = true;
					}
				}
			} while (swapped);
			
			// Сохраняем результат
			results[k - 1] = energy;
		}
		
		// Выводим результаты
		for (int i = 0; i < n; i++) {
			System.out.print(results[i] + " ");
		}
	}
}
